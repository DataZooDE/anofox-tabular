"""
Shared table lifecycle helpers for wrappers that accept table names or DataFrames.
"""

from __future__ import annotations

import functools
import inspect
import re
from contextlib import contextmanager
from typing import Any, Callable, Iterator, Optional, TypeVar, Union

from ._sql import fetch_frame, quote_ident
from ._utils import (
    detect_df_type,
    drop_df_table,
    register_df_as_table,
    registered_view,
)


F = TypeVar("F", bound=Callable[..., Any])

#: A table name, or a pandas/polars DataFrame standing in for one.
TableLike = Union[str, Any]


def resolve_table(conn: Any, table_or_df: Union[str, Any]) -> tuple[str, bool]:
    """
    Return ``(table_name, was_registered)``.

    If *table_or_df* is a DataFrame, it is materialized as a temporary table.
    """
    if isinstance(table_or_df, str):
        return table_or_df, False
    try:
        detect_df_type(table_or_df)  # validate type before registering
    except TypeError as error:
        if "Series" in str(error):
            raise
        raise TypeError(
            f"pass a table name or a DataFrame (pandas or polars), got {_describe(table_or_df)}"
        ) from None
    table_name = register_df_as_table(conn.native, table_or_df)
    return table_name, True


#: A table or view name generated by :func:`~anofox._utils.register_df_as_table` /
#: :func:`~anofox._utils.registered_view`, optionally quoted and preceded by
#: "table", "source table", "target table", "source" or "target" (which the replacement
#: "the DataFrame" / "the source DataFrame" makes redundant).
_TEMP_NAME = re.compile(
    r"""(?P<word>\b(?:(?:source|target)\s+)?table\s+|\b(?:source|target)\s+)?(?P<q>['"]?)"""
    r"""(?P<name>_anofox_(?:v_)?[0-9a-f]{32}(?:_v)?)(?P=q)""",
    re.IGNORECASE,
)


def _temp_name_label(match: "re.Match[str]", labels: dict) -> str:
    label = labels.get(match.group("name"), "the DataFrame")
    word = match.group("word") or ""
    return label[0].upper() + label[1:] if word[:1].isupper() else label


def without_temp_names(text: str, labels: Optional[dict] = None) -> str:
    """*text* with every generated temporary table name replaced (see :func:`hide_temp_names`)."""
    if "_anofox_" not in text:
        return text
    return _TEMP_NAME.sub(lambda m: _temp_name_label(m, labels or {}), text)


def hide_temp_names(error: BaseException, labels: Optional[dict] = None) -> None:
    """
    Replace generated temporary table names in *error*'s message, in place.

    A name found in *labels* becomes its label (e.g. ``"the source DataFrame"``),
    any other generated name ``"the DataFrame"``; a preceding "table",
    "source (table)" or "target (table)" is dropped (``"in table '_anofox_...'"`` becomes
    ``"in the DataFrame"``). The exception keeps its type and traceback.
    """
    args = getattr(error, "args", ())
    if not args or not isinstance(args[0], str) or "_anofox_" not in args[0]:
        return
    message = without_temp_names(args[0], labels)
    try:
        error.args = (message, *args[1:])
    except (AttributeError, TypeError):  # pragma: no cover - exotic exception types
        pass


@contextmanager
def table_inputs(conn: Any, *inputs: Union[str, Any], labels: Optional[list] = None) -> Iterator[list]:
    """
    Resolve each of *inputs* (table name or DataFrame) to a table name for the block.

    DataFrames are copied into temporary tables (see :func:`resolve_table`)
    that are dropped when the block ends, also when resolving a later input
    fails. An error raised in the block names a DataFrame input by its label
    (default ``"the DataFrame"``) instead of its generated table name.
    """
    resolved: list = []
    created: dict = {}
    try:
        for index, value in enumerate(inputs):
            name, registered = resolve_table(conn, value)
            resolved.append(name)
            if registered:
                created[name] = labels[index] if labels else "the DataFrame"
        yield resolved
    except Exception as error:
        hide_temp_names(error, created)
        raise
    finally:
        for name in created:
            cleanup_table(conn, name, True)


def check_row_input(value: Any, column: Optional[str]) -> str:
    """
    Validate the DataFrame input of a row-wise wrapper and return its type.

    Raises TypeError for a Series, None or any other non-DataFrame object, and
    ValueError when *column* is missing or not a column of the DataFrame.
    """
    if type(value).__name__ == "Series" and type(value).__module__.split(".")[0] in ("pandas", "polars"):
        raise TypeError(
            "expected a string or a pandas/polars DataFrame, got a Series; "
            "pass series.to_frame() with column=series.name"
        )
    try:
        df_type = detect_df_type(value)
    except TypeError:
        raise TypeError(
            f"expected a string or a pandas/polars DataFrame, got {_describe(value)}"
        ) from None
    if column is None:
        raise ValueError("'column' is required when passing a DataFrame.")
    columns = [str(c) for c in value.columns]
    if column not in columns:
        raise ValueError(
            f"column {column!r} not found in the DataFrame; its columns are "
            f"{', '.join(map(repr, columns))}"
        )
    return df_type


def accepts_dataframes(*param_names: str) -> Callable[[F], F]:
    """
    Decorator: let the parameters *param_names* (table names) also take a
    pandas or polars DataFrame.

    Each DataFrame is copied into a temporary table (see :func:`table_inputs`)
    for the duration of the call and dropped afterwards; an error message
    calls it "the DataFrame" instead of the generated table name.
    """
    def decorator(func: F) -> F:
        signature = inspect.signature(func)

        @functools.wraps(func)
        def wrapper(conn: Any, *args: Any, **kwargs: Any) -> Any:
            bound = signature.bind(conn, *args, **kwargs)
            names = [name for name in param_names if name in bound.arguments]
            with table_inputs(conn, *(bound.arguments[name] for name in names)) as tables:
                bound.arguments.update(zip(names, tables))
                return func(*bound.args, **bound.kwargs)

        return wrapper  # type: ignore[return-value]

    return decorator


def _describe(value: Any) -> str:
    """Short description of *value*'s type for error messages."""
    if value is None:
        return "None"
    cls = type(value)
    module = cls.__module__.split(".")[0]
    return f"{module}.{cls.__qualname__}" if module != "builtins" else cls.__qualname__


def output_df_type(*inputs: Any) -> str:
    """
    DataFrame library for a result: ``"polars"`` when the first DataFrame among
    *inputs* is a polars DataFrame, else ``"pandas"`` (also for table names).
    """
    for value in inputs:
        if not isinstance(value, str):
            return detect_df_type(value)
    return "pandas"


def cleanup_table(conn: Any, table_name: str, was_registered: bool) -> None:
    """Drop a table only when it was created by :func:`resolve_table`."""
    if was_registered:
        drop_df_table(conn.native, table_name)


def apply_scalar(
    conn: Any,
    df: Any,
    df_type: str,
    expression: str,
    params: list,
    result_name: str,
) -> Any:
    """
    Return a copy of *df* with one added column *result_name*.

    If *df* already has a column *result_name*, that column is replaced in
    place (``pii_mask(..., replace=True)`` relies on this).

    *expression* is a SQL expression over the columns of *df* (identifiers
    already quoted) with ``?`` placeholders for *params*. The result keeps the
    input's rows in their order, its other columns unchanged and, for pandas,
    its index, so the new column can be assigned back to the input.
    """
    with registered_view(conn.native, df) as (view, position):
        result = fetch_frame(
            conn,
            f"SELECT {expression} AS {quote_ident(result_name)} "
            f"FROM {quote_ident(view)} ORDER BY {quote_ident(position)}",
            params,
            df_type,
        )
        if df_type == "pandas":
            values = result[result_name]
            values.index = df.index
            out = df.copy()
            out[result_name] = values
            return out
        values = result.get_column(result_name)
        return df.with_columns(values)
