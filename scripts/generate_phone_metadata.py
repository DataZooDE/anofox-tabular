"""Generate src/anofox_phonenumber_metadata_data.inc from libphonenumber metadata.

The phone module (src/anofox_phonenumber*.cpp) implements libphonenumber's parsing,
validation and formatting rules in C++; the per-region data comes from the metadata
that the `phonenumbers` package (the Python port of libphonenumber) ships. To update
the data, bump the version pin above, in python/pyproject.toml and in
.github/workflows/_extension_smoke_test.yml (the parity test compares against the same
version), then run from the repository root:

    uv run scripts/generate_phone_metadata.py

The output is constant-initialised C++ (string_view and integers only): no work at
load time, and the regular expressions are compiled per region on first use.

Non-geographic entities (+800, +882, ...: region "001") are not included; numbers
with those country codes are reported as unsupported_country_code.
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

import phonenumbers
from phonenumbers import PhoneMetadata

OUTPUT = Path(
    os.environ.get(
        "ANOFOX_PHONE_METADATA_OUT",
        Path(__file__).resolve().parent.parent / "src" / "anofox_phonenumber_metadata_data.inc",
    )
)

# Number types in the order of CountryMetadata's NumberDesc members
DESC_FIELDS = [
    "general_desc",
    "fixed_line",
    "mobile",
    "toll_free",
    "premium_rate",
    "shared_cost",
    "personal_number",
    "voip",
    "pager",
    "uan",
    "voicemail",
]

# Deliberate deviations from upstream, each covered by a test.
OVERRIDES: dict[str, dict[str, str]] = {
    # Mexico dropped the national prefix 01/02 and the mobile prefixes 044/045 and
    # "+52 1" in 2019 (libphonenumber removed them from parsing in v8.13.38). Old
    # customer data still holds them, so they are dropped when parsing, as
    # libphonenumber did from v8.10.17 to v8.13.37 (test/sql/anofox_phonenumber_mx.test).
    "MX": {"national_prefix_for_parsing": "0(?:[12]|4[45])|1"},
}


def check_groups(pattern: str | None, where: str) -> None:
    """The C++ code reads at most $0..$9 (MAX_PATTERN_GROUPS)."""
    if pattern and re.compile(pattern).groups > 9:
        sys.exit(f"{where}: pattern {pattern!r} has more than 9 capture groups")


def cpp_string(value: str | None) -> str:
    if not value:
        return '""'
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def java_rule(value: str) -> str:
    """Python group references (\\1) to the $1 form the C++ code expands."""
    return re.sub(r"\\(\d)", r"$\1", value)


def length_mask(lengths) -> str:
    mask = 0
    for length in lengths or ():
        if length < 0:
            continue
        if length > 31:
            sys.exit(f"possible length {length} does not fit the 32-bit mask")
        mask |= 1 << length
    return f"0x{mask:08x}u"


def number_desc(desc) -> str:
    if desc is None:
        return '{"", 0x00000000u, 0x00000000u, ""}'
    return (
        "{"
        f"{cpp_string(desc.national_number_pattern)}, "
        f"{length_mask(desc.possible_length)}, "
        f"{length_mask(desc.possible_length_local_only)}, "
        f"{cpp_string(desc.example_number)}"
        "}"
    )


def national_format(fmt, national_prefix: str) -> str:
    """The NATIONAL layout: the format with its first group replaced by the
    national-prefix formatting rule ("0$1"), as libphonenumber's formatNsnUsingPattern."""
    layout = java_rule(fmt.format)
    rule = fmt.national_prefix_formatting_rule
    if not rule:
        return layout
    rule = java_rule(rule).replace("$NP", national_prefix or "").replace("$FG", "$1")
    first = re.search(r"\$\d", layout)
    if not first:
        return layout
    return layout[: first.start()] + rule.replace("$1", first.group(0)) + layout[first.end() :]


def leading_digits(fmt) -> str:
    # libphonenumber uses the last (most specific) leading-digits pattern
    patterns = fmt.leading_digits_pattern or []
    return patterns[-1] if patterns else ""


def format_entry(fmt, layout: str) -> str:
    check_groups(fmt.pattern, "number format")
    return f"\t{{{cpp_string(leading_digits(fmt))}, {cpp_string(fmt.pattern)}, {cpp_string(layout)}}},"


def main() -> None:
    regions = sorted(phonenumbers.SUPPORTED_REGIONS)
    out: list[str] = []
    out.append(
        f"// GENERATED by scripts/generate_phone_metadata.py from phonenumbers {phonenumbers.__version__}\n"
        "// (libphonenumber metadata). Do not edit; regenerate instead.\n"
        "// Included by src/anofox_phonenumber_metadata.cpp.\n"
        "// clang-format off\n"
    )
    out.append(f'constexpr const char *PHONE_METADATA_VERSION = "{phonenumbers.__version__}";\n')
    out.append("namespace {\n")

    region_entries: list[str] = []
    for region in regions:
        meta = PhoneMetadata.metadata_for_region(region)
        override = OVERRIDES.get(region, {})
        national_prefix = meta.national_prefix or ""
        npfp = override.get(
            "national_prefix_for_parsing", meta.national_prefix_for_parsing or national_prefix
        )
        transform = java_rule(meta.national_prefix_transform_rule or "")
        check_groups(npfp, f"{region} national_prefix_for_parsing")

        national = [format_entry(f, national_format(f, national_prefix)) for f in meta.number_format]
        if meta.intl_number_format:
            intl = [format_entry(f, java_rule(f.format)) for f in meta.intl_number_format if f.format != "NA"]
        else:
            intl = [format_entry(f, java_rule(f.format)) for f in meta.number_format]

        def emit_formats(name: str, entries: list[str]) -> str:
            if not entries:
                return "nullptr, 0"
            out.append(f"const NumberFormat {name}[] = {{\n" + "\n".join(entries) + "\n};")
            return f"{name}, {len(entries)}"

        national_ref = emit_formats(f"NATIONAL_FORMATS_{region}", national)
        intl_ref = emit_formats(f"INTL_FORMATS_{region}", intl)

        descs = ",\n\t ".join(number_desc(getattr(meta, field)) for field in DESC_FIELDS)
        region_entries.append(
            f"\t{{\"{region}\", {meta.country_code}, "
            f"{cpp_string(meta.international_prefix)}, {cpp_string(national_prefix)}, "
            f"{cpp_string(npfp)}, {cpp_string(transform)}, {cpp_string(meta.leading_digits)}, "
            f"{'true' if meta.same_mobile_and_fixed_line_pattern else 'false'},\n"
            f"\t {{{{{descs}}}}},\n"
            f"\t {national_ref}, {intl_ref}}},"
        )

    out.append("} // namespace\n")
    out.append(f"constexpr size_t REGION_COUNT = {len(regions)};\n")
    out.append("// Sorted by region code (binary search)")
    out.append("const CountryMetadata REGION_METADATA_TABLE[REGION_COUNT] = {\n" + "\n".join(region_entries) + "\n};\n")

    codes = sorted(
        (code, regs)
        for code, regs in phonenumbers.COUNTRY_CODE_TO_REGION_CODE.items()
        if any(r in phonenumbers.SUPPORTED_REGIONS for r in regs)
    )
    out.append("namespace {")
    code_entries = []
    for code, regs in codes:
        regs = [r for r in regs if r in phonenumbers.SUPPORTED_REGIONS]
        name = f"COUNTRY_CODE_REGIONS_{code}"
        out.append(f"const std::string_view {name}[] = {{" + ", ".join(f'"{r}"' for r in regs) + "};")
        code_entries.append(f"\t{{{code}, {name}, {len(regs)}}},")
    out.append("} // namespace\n")
    out.append(f"constexpr size_t COUNTRY_CODE_COUNT = {len(codes)};\n")
    out.append("// Sorted by country code; the first region of each entry is the main region")
    out.append(
        "const CountryCodeRegions COUNTRY_CODE_TABLE[COUNTRY_CODE_COUNT] = {\n" + "\n".join(code_entries) + "\n};"
    )
    out.append("// clang-format on")

    OUTPUT.write_text("\n".join(out) + "\n")
    print(f"wrote {OUTPUT} ({len(regions)} regions, {len(codes)} country codes)")


if __name__ == "__main__":
    main()
